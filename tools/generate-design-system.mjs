/* ---------- tokens and rules, read from the stylesheet ---------- */
const css = read('src/styles/base.css');
const rootBlock = css.match(/:root\s*\{([\s\S]*?)\}/);
if (!rootBlock) throw new Error('base.css: no :root block');
const tokens = Object.fromEntries([...rootBlock[1].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const group = (test) => Object.entries(tokens).filter(([k]) => test(k));
const colours = group((k) => /^--(acid|malachite|bottle|void|flash|shock)$/.test(k));
const motion = group((k) => /^--(t-|ease|stepped)/.test(k));
const spacing = group((k) => /^--gutter/.test(k));
const type = group((k) => /^--fs-/.test(k));
const seen = new Set([...colours, ...motion, ...spacing, ...type].map(([k]) => k));
const rest = group((k) => !seen.has(k));
if (rest.length) throw new Error('base.css: tokens with no group: ' + rest.map(([k]) => k).join(', '));

const tokenFile = (title, entries) => `/* ${title}. Read from src/styles/base.css by tools/generate-design-system.mjs; edit there. */\n:root {\n${entries.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;
write('tokens/colors.css', tokenFile('Aedificare colour tokens. Six, no tints, no grey', colours));
write('tokens/typography.css', tokenFile('Aedificare type scale', type));
write('tokens/spacing.css', tokenFile('Aedificare spacing', spacing));
write('tokens/motion.css', tokenFile('Aedificare motion: two durations, one stepped curve, one ease', motion));

const faces = [...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map((m) => m[0].replace(/url\('\/fonts\//g, "url('../assets/fonts/"));
if (faces.length !== 2) throw new Error('base.css: expected two @font-face blocks');
write('tokens/fonts.css', `/* The two faces, the shipped subsets, every axis kept. From src/styles/base.css. */\n${faces.join('\n')}\n`);

let rules = css.replace(/^\/\*[\s\S]*?\*\/\s*/, '').replace(/:root\s*\{[\s\S]*?\}\s*/, '').replace(/@font-face\s*\{[^}]*\}\s*/g, '');
const scoped = ['src/components/Masthead.astro', 'src/components/EditionEnd.astro'].map((f) => {
  const m = read(f).match(/<style>([\s\S]*?)<\/style>/);
  if (!m) throw new Error(f + ': no style block');
  return `/* from ${f} (scoped there, global here) */\n` + m[1].replace(/:global\(([^)]*)\)/g, '$1').trim();
});
write('styles.css', `/* Aedificare design system: global CSS entry point.
   Tokens and fonts are imported; everything below the imports is
   src/styles/base.css as shipped, then the rules the site keeps scoped
   inside components. Generated by tools/generate-design-system.mjs at
   ${head} on ${today}; edit the site, not this file. */
@import "tokens/fonts.css";
@import "tokens/colors.css";
@import "tokens/typography.css";
@import "tokens/spacing.css";
@import "tokens/motion.css";

${rules.trim()}

${scoped.join('\n\n')}
`);

