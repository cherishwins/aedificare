/**
 * The design system, generated from the site.
 *
 * claude.ai/design keeps one project per brand: tokens, fonts, specimen
 * cards and React primitives, which the design app and its agents compose
 * new surfaces from. Typed copies of a stylesheet drift, so this bundle is
 * never typed: the tokens are read out of src/styles/base.css, the rules
 * are base.css itself with the font paths rewritten, the component-scoped
 * rules are lifted from the .astro files, every rose is computed by the
 * same rhodonea() as the site (its source is copied into the React
 * components by this script, never by hand), and the fonts and marks are
 * the shipped files. Regenerate after any change to the stylesheet, the
 * rose library or the editions, then push with /design-sync.
 *
 *   node tools/generate-design-system.mjs
 *
 * Output: design-system/ (gitignored; the claude.ai project is the copy
 * that matters). Project id and namespace are constants below because the
 * component cards address the compiled bundle by namespace.
 */
